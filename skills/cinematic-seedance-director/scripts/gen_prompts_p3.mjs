/** 依据本段实际拍点，收集出现的角色 / 道具 / 音色 */
function collectAssets(seg) {
  const chars = new Set();
  const props = new Set();
  const voices = new Set();
  const text = JSON.stringify(seg.detail);
  for (const name of Object.keys(CHAR_FILE)) if (text.includes(name)) chars.add(name);
  // 公车鬼在 10-1 场必然在场（space 里写死）
  if (seg.scene === "10-1") chars.add("公车鬼");
  for (const name of Object.keys(PROP_FILE)) if (text.includes(name)) props.add(name);
  for (const d of seg.detail) if (d.dialogueZh && d.speaker) voices.add(d.speaker);
  // 系统面板：本段有面板文字或属于 10-1 场时列出
  if (/(系统|面板|捕捉|字幕)/u.test(text) || seg.panelCount > 0) props.add("系统面板");
  return { chars: [...chars], props: [...props], voices: [...voices] };
}

/** 生成「资产清单」头部栏（放在风格声明之后、场景概述之前） */
function buildAssetBlock(seg) {
  const { chars, props, voices } = collectAssets(seg);
  const sc = SCENE_FILE[seg.scene];
  const L = [];
  L.push("【资产清单·可直接@引用参考图】");
  L.push(`【场景】@${sc.file}　${sc.desc}`);
  L.push(`【角色】${chars.length ? chars.map((c) => `@${CHAR_FILE[c].file} ${CHAR_FILE[c].desc}`).join("\n　　　　") : "本段无角色出场"}`);
  L.push(`【音色】${voices.length ? voices.map((v) => `@${VOICE_FILE[v] ? VOICE_FILE[v].file : v} ${VOICE_FILE[v] ? VOICE_FILE[v].desc : v}`).join("\n　　　　") : "本段无台词"}`);
  L.push(`【道具】${props.length ? props.map((p) => `@${PROP_FILE[p].file} ${PROP_FILE[p].desc}`).join("\n　　　　") : "本段无关键道具"}`);
  L.push("（注：以上为可选参考图绑定；若未上传对应素材，请忽略 @ 标记，直接按下方文字描述生成。）");
  return L.join("\n");
}

