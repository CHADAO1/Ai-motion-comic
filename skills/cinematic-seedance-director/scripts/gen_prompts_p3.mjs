// ── 镜头编排：把拍点映射为镜头；单镜 ≥6s 时按 3–5s 切分为多镜（满足 AW-02 ≥3s 禁固定 + 常规 ≤5s）──
function buildShots(seg) {
  const shots = [];
  let t = 0;
  for (const d of seg.detail) {
    let remain = d.seconds;
    const parts = [];
    while (remain > 1e-9) {
      // 目标单镜 3–5s；不足 3s 的余量并入上一镜，避免出现 <3s 的碎镜
      let take = remain >= 6 ? Math.min(5, remain) : remain;
      if (remain - take > 0 && remain - take < 3) take = remain;
      parts.push(r1(take));
      remain = r1(remain - take);
    }
    parts.forEach((take, pi) => {
      const isLast = pi === parts.length - 1;
      shots.push({
        ...d, part: pi + 1, parts: parts.length,
        t0: r1(t), t1: r1(t + take), seconds: take,
        // 台词/面板只在**最后**一个子镜出现一次，避免重复渲染；无台词拍则平均分配
        dialogueZh: isLast ? d.dialogueZh : "",
        panel: isLast ? d.panel : [],
        halfDialogue: !isLast && d.dialogueZh ? "" : undefined
      });
      t = r1(t + take);
    });
  }
  // 若末镜 <3s，与前镜合并
  if (shots.length >= 2) {
    const last = shots[shots.length - 1];
    if (last.t1 - last.t0 < 3 - 1e-9) {
      const prev = shots[shots.length - 2];
      prev.t1 = last.t1; prev.seconds = r1(prev.t1 - prev.t0);
      prev.dialogueZh = prev.dialogueZh || last.dialogueZh;
      prev.panel = [...(prev.panel ?? []), ...(last.panel ?? [])];
      shots.pop();
    }
  }
  return shots;
}

